// Generates plugin/dsp/src/poly/profile_data.h from js/audio/guitar/poly/profile.js,
// the measured guitar profile behind the generic POLY template bank
// (docs/plugin-plan.md, section 5 M3 task 1). The JavaScript stays canonical:
// the numbers are those V8 parsed from profile.js, printed with 17 significant
// digits (exact round trip) and, next to them, as IEEE-754 bit patterns that
// plugin/dsp/tests/test_poly_bank.cpp compares against what the C++ compiler
// parsed (any rounding difference fails the test).
//
//   node plugin/tools/gen-profile-header.mjs           rewrite the header
//   node plugin/tools/gen-profile-header.mjs --check   exit 1 if the committed header is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { B_LAW, PROF_ATT, PROF_DEC } from '../../js/audio/guitar/poly/profile.js';

const OUT = fileURLToPath(new URL('../dsp/src/poly/profile_data.h', import.meta.url));

const dv = new DataView(new ArrayBuffer(8));
const bits = x => { dv.setFloat64(0, x); return '0x' + dv.getBigUint64(0).toString(16).toUpperCase().padStart(16, '0') + 'ull'; };
const num = x => {
  if (!Number.isFinite(x)) throw new Error(`profile.js holds a non-finite number: ${x}`);
  let s = x.toPrecision(17);
  if (!/[.e]/.test(s)) s += '.0';
  return s;
};

function table(name, rows, fmt, type) {
  const cols = rows[0].length;
  for (const r of rows) if (r.length !== cols) throw new Error(`${name}: ragged rows`);
  const body = rows.map(r => '        { ' + r.map(fmt).join(', ') + ' }').join(',\n');
  return `    inline constexpr ${type} ${name}[${rows.length}][${cols}] = {\n${body}\n    };\n`;
}

function render() {
  return [
    '// GENERATED by plugin/tools/gen-profile-header.mjs from js/audio/guitar/poly/profile.js.',
    '// Do not edit by hand: change profile.js (test/poly/export-profile.py) and rerun',
    '//   node plugin/tools/gen-profile-header.mjs',
    '// The CI and test_poly_bank check that this file is up to date and parsed bit-exactly.',
    '//',
    '// Strings are indexed 0..5 = low E .. high E.',
    '//   B_LAW[s]    = { B_open_fit, slope_per_6_frets }: B(fret f) = B_open_fit * 2^(f * slope / 6)',
    '//   PROF_ATT[s] = median partial-amplitude profile of the attack (partials 1..40)',
    '//   PROF_DEC[s] = same for the decay phase (kept for a future "dec" bank)',
    '#pragma once',
    '',
    '#include <cstdint>',
    '',
    'namespace midpluck::poly::generated',
    '{',
    table('B_LAW', B_LAW, num, 'double'),
    table('PROF_ATT', PROF_ATT, num, 'double'),
    table('PROF_DEC', PROF_DEC, num, 'double'),
    '    // The same numbers as IEEE-754 bit patterns, as V8 parsed profile.js.',
    table('B_LAW_BITS', B_LAW, bits, 'std::uint64_t'),
    table('PROF_ATT_BITS', PROF_ATT, bits, 'std::uint64_t'),
    table('PROF_DEC_BITS', PROF_DEC, bits, 'std::uint64_t'),
    '}',
    '',
  ].join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing = stale */ }
  if (cur.replace(/\r\n/g, '\n') !== text) {
    console.error(`${OUT} is stale: run node plugin/tools/gen-profile-header.mjs`);
    process.exit(1);
  }
  console.error(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, text);
  console.error(`wrote ${OUT}`);
}
